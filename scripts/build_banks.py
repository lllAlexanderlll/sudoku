#!/usr/bin/env python3
"""Builds the pre-computed puzzle banks and writes them into index.html.

Inputs
  --ph2010 DIR      PUZZLES directory of the ph2010 "potential hardest" collection
                    (denis-berthier/Sudoku-classif, ph2010-3103972-TE2/PUZZLES), lines
                    "puzzle;ER;EP;ED;...;name;id;clues" with Sudoku Explainer ratings.
  --rated FILE:TAG  Sudoku Explainer (serate) output "puzzle ER/EP/ED technique".
                    TAG G = generated by tools/ (Schwer, Experte), N = new vicinity find,
                    C = only used to look up ratings of the named classics.
  --tool PATH       tools/target/release/sudoku-tools
Every selected puzzle is re-verified (unique solution, minimal), and no two puzzles in the
banks share a solution grid (by isomorphism-invariant fingerprint).
Outputs: data/puzzles.csv (all puzzles with solutions) and the BANK block in index.html.
"""
import argparse, csv, glob, os, random, re, subprocess, sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# level: (min ER, max ER, bank size, spread). spread=True: round-robin over the distinct rating
# values so that every difficulty within the level is equally represented; False: hardest first.
LEVELS = {
    'schwer':  (2.6, 4.4, 500, True),
    'experte': (4.5, 8.9, 800, True),
    'meister': (9.0, 11.3, 800, True),
    'extrem':  (11.4, 11.9, 1000, False),
}


NEW_SHARE = 0.4  # at most this share of a spread bank comes from new vicinity finds


def round_robin(items, n, rng):
    """Picks up to n items, cycling over the distinct rating values so that every difficulty
    is equally represented; sparse values give their share to the others."""
    by_value = defaultdict(list)
    for it in items:
        by_value[it['er']].append(it)
    groups = [by_value[v] for v in sorted(by_value)]
    for g in groups:
        rng.shuffle(g)
    out, i = [], 0
    while len(out) < n and any(groups):
        g = groups[i % len(groups)]
        if g:
            out.append(g.pop())
        i += 1
    return out


def tool(args, lines):
    out = subprocess.run([ARGS.tool] + args, input='\n'.join(lines) + '\n', capture_output=True, text=True, check=True).stdout
    return [l.split() for l in out.splitlines()]


def level_of(er):
    for k, (lo, hi, _, _) in LEVELS.items():
        if lo - 1e-9 <= er <= hi + 1e-9:
            return k
    return None


def load():
    """Returns list of dicts: p, er, src (F famous, N new, R ranking list, G generated), name."""
    items = []
    for f in sorted(glob.glob(os.path.join(ARGS.ph2010, 'puzzles-*.txt'))):
        for line in open(f):
            x = line.rstrip('\n').split(';')
            if len(x) > 5 and len(x[0]) == 81:
                items.append({'p': x[0], 'er': float(x[1]), 'src': 'R', 'name': x[5].strip()})
    print(f'ph2010: {len(items)} puzzles', file=sys.stderr)
    for spec in ARGS.rated:
        path, tag = spec.rsplit(':', 1)
        n = 0
        for line in open(path):
            m = re.match(r'([.0-9]{81})\s+(\d+\.\d)/', line)
            if m:
                items.append({'p': m.group(1).replace('0', '.'), 'er': float(m.group(2)), 'src': tag, 'name': ''})
                n += 1
        print(f'{path}: {n} rated puzzles ({tag})', file=sys.stderr)
    return items


def main():
    rng = random.Random(20261121)
    items = load()
    famous = [l.rstrip('\n').split('\t') for l in open(os.path.join(ROOT, 'data/famous.tsv'), encoding='utf-8') if not l.startswith('#')]

    # Ratings for the named classics are looked up in the rated pools by fingerprint.
    fam_rows = tool(['fp'], [g for _, g in famous])
    pools = defaultdict(list)
    for it in items:
        k = level_of(it['er'])
        if k and it['src'] in 'RGN':  # tag C: ratings only used for the named classics
            pools[k].append(it)
    # ph2010 has ~3M puzzles; for Meister sample a manageable, rating-stratified subset first.
    meister_r = [it for it in pools['meister'] if it['src'] == 'R']
    by_er = defaultdict(list)
    for it in meister_r:
        by_er[it['er']].append(it)
    sampled = []
    for er, lst in by_er.items():
        rng.shuffle(lst)
        sampled += lst[:600]
    pools['meister'] = [it for it in pools['meister'] if it['src'] != 'R'] + sampled

    # fingerprint everything still in play
    cand = [it for k in LEVELS for it in pools[k]]
    fps = tool(['fp'], [it['p'] for it in cand])
    for it, row in zip(cand, fps):
        it['pfp'], it['gfp'] = row[1], row[2]
    # drop anything without a unique solution or not minimal (the lists contain a few)
    ok = {r[0] for r in tool(['check'], [it['p'] for it in cand]) if r[1] == '1' and r[2] == '1'}
    for k in LEVELS:
        before = len(pools[k])
        pools[k] = [it for it in pools[k] if it['p'] in ok]
        if len(pools[k]) < before:
            print(f'{k}: dropped {before - len(pools[k])} non-unique or non-minimal puzzles', file=sys.stderr)
    # the hardest levels must need two nested levels of trial and error (T&E depth 2)
    for k in ('meister', 'extrem'):
        depth = {r[0]: r[1] for r in tool(['ted', '2'], [it['p'] for it in pools[k]])}
        before = len(pools[k])
        pools[k] = [it for it in pools[k] if depth[it['p']] == '2' or it['src'] == 'G']
        print(f'{k}: {before - len(pools[k])} dropped for T&E depth != 2', file=sys.stderr)

    # find the classics' ratings among all ph2010 entries if not already in play
    want = {r[1] for r in fam_rows}
    found = {it['pfp']: it['er'] for it in cand if it['pfp'] in want}
    others = [it for it in items if it['src'] != 'R' and 'pfp' not in it]
    for it, row in zip(others, tool(['pfp'], [it['p'] for it in others])):
        if row[0] in want:
            found.setdefault(row[0], it['er'])
    missing = want - set(found)
    if missing:
        r_items = [it for it in items if it['src'] == 'R']
        for it, row in zip(r_items, tool(['pfp'], [it['p'] for it in r_items])):
            if row[0] in missing:
                found[row[0]] = it['er']
    fam_items = []
    for (name, g), row in zip(famous, fam_rows):
        if row[1] in found:
            fam_items.append({'p': g, 'er': found[row[1]], 'src': 'F', 'name': name, 'pfp': row[1], 'gfp': row[2]})
    if len(fam_items) < len(famous):
        miss = [g for (name, g), row in zip(famous, fam_rows) if row[1] not in found]
        sys.exit('no rating found for these classics (rate them with serate and pass --rated FILE:C):\n' + '\n'.join(miss))
    for it in fam_items:
        pools[level_of(it['er']) or 'extrem'].append(it)

    prio = {'F': 0, 'N': 1, 'R': 2, 'G': 3}
    banks = {}
    seen_g = set()  # solution grids already used, across banks: no near-twins between levels
    for k in reversed(list(LEVELS)):  # hardest first, so the hard banks get first pick of grids
        lo, hi, size, spread = LEVELS[k]
        pool = pools[k]
        rng.shuffle(pool)
        # classics first, then new finds, then hardest; drop duplicates by puzzle and by solution grid
        pool.sort(key=lambda it: (prio[it['src']], -it['er']))
        seen_p, local_g, uniq = set(), set(), []
        for it in pool:
            dup_grid = it['gfp'] in local_g or it['gfp'] in seen_g
            if it['pfp'] in seen_p or (dup_grid and it['src'] != 'F'):  # classics are always kept
                continue
            seen_p.add(it['pfp']); local_g.add(it['gfp'])
            uniq.append(it)
        if not spread:
            chosen = uniq[:size]
        else:
            chosen = [it for it in uniq if it['src'] == 'F']
            # new finds take at most NEW_SHARE of the bank, then the rest is filled up
            new = [it for it in uniq if it['src'] == 'N']
            chosen += round_robin(new, int(size * NEW_SHARE) - len(chosen), rng)
            taken = {id(it) for it in chosen}
            rest = [it for it in uniq if id(it) not in taken and it['src'] != 'N']
            chosen += round_robin(rest, size - len(chosen), rng)
        for it in chosen:
            seen_g.add(it['gfp'])
        banks[k] = chosen
        print(f'{k}: pool {len(pool)}, unique grids {len(uniq)}, chosen {len(chosen)}', file=sys.stderr)

    banks = {k: banks[k] for k in LEVELS}
    # verify: unique solution and minimal
    allp = [it['p'] for k in banks for it in banks[k]]
    rows = tool(['check'], allp)
    bad = [r[0] for r in rows if r[1] != '1' or r[2] != '1']
    if bad:
        sys.exit(f'{len(bad)} puzzles failed verification, e.g. {bad[0]}')
    solution = {r[0]: r[4] for r in rows}
    print(f'verified {len(allp)} puzzles: unique and minimal', file=sys.stderr)

    # data/puzzles.csv: every embedded puzzle with its solution, for use outside this repository
    SOURCE = {'F': 'classic', 'N': 'new', 'R': 'ranking-list', 'G': 'generated'}
    with open(os.path.join(ROOT, 'data/puzzles.csv'), 'w', encoding='utf-8', newline='') as f:
        w = csv.writer(f, lineterminator='\n')
        w.writerow(['level', 'puzzle', 'solution', 'rating', 'source', 'name'])
        for k, lst in banks.items():
            lst.sort(key=lambda it: (-it['er'], it['p']))
            for it in lst:
                w.writerow([k, it['p'], solution[it['p']], f"{it['er']:.1f}", SOURCE[it['src']],
                            it['name'] if it['src'] in 'FR' else ''])
            hist = defaultdict(int)
            for it in lst:
                hist[it['er']] += 1
            print(k, ' '.join(f'{e:.1f}:{n}' for e, n in sorted(hist.items())), file=sys.stderr)

    write_html(banks)


def write_html(banks):
    """Replaces the block between BANK-START and BANK-END in index.html."""
    js = ['// BANK-START (generated from data/puzzles.csv by scripts/build_banks.py or scripts/csv_to_page.mjs, do not edit by hand)',
          '/* Je Eintrag: 81 Zeichen Rätsel, 3 Ziffern Bewertung (114 = 11,4), 1 Zeichen Herkunft',
          '   (F bekanntes Rätsel, N neu gefunden, R Forums-Rangliste, G vorab erzeugt). */',
          'const NAMED = {']
    for k, lst in banks.items():
        for it in lst:
            if it['src'] == 'F':
                js.append(f"  {it['p']!r}: {it['name']!r},")
    js.append('};')
    js.append('const BANK = {')
    for k, lst in banks.items():
        body = '\n'.join(f"{it['p']}{round(it['er'] * 10):03d}{it['src']}" for it in lst)
        js.append(f'  {k}: `\n{body}`,')
    js.append('};')
    js.append('// BANK-END')
    path = os.path.join(ROOT, 'index.html')
    html = open(path, encoding='utf-8').read()
    new, n = re.subn(r'// BANK-START.*?// BANK-END', lambda m: '\n'.join(js), html, flags=re.S)
    if n != 1:
        sys.exit('BANK-START/BANK-END markers not found in index.html')
    open(path, 'w', encoding='utf-8').write(new)
    print(f'wrote index.html ({len(new) // 1024} KB)', file=sys.stderr)


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--ph2010', required=True)
    ap.add_argument('--rated', action='append', default=[])
    ap.add_argument('--tool', default=os.path.join(ROOT, 'tools/target/release/sudoku-tools'))
    ARGS = ap.parse_args()
    main()
